export function listSubjects(classLevel: ClassLevel): Subject[] {
  return curriculum.filter((s) => s.classLevel === classLevel);
}

export function getSubject(classLevel: ClassLevel, subjectId: string): Subject | undefined {
  return curriculum.find((s) => s.classLevel === classLevel && s.id === subjectId);
}

export function getChapter(chapterId: string): Chapter | undefined {
  for (const subject of curriculum) {
    const found = subject.chapters.find((c) => c.id === chapterId);
    if (found) return found;
  }
  return undefined;
}
